import { chromium } from "@playwright/test";
const BASE = "http://localhost:3000";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const page = await ctx.newPage();
await page.goto(`${BASE}/login`, { waitUntil: "networkidle", timeout: 60000 });
await page.waitForTimeout(1500);
await page.getByLabel("Email").fill("admin@sanjivani.test");
await page.getByLabel("Password").fill("Passw0rd!");
await page.waitForFunction(() => document.querySelector("#email")?.value === "admin@sanjivani.test", null, { timeout: 10000 });
await page.getByRole("button", { name: /log in/i }).click();
await page.waitForURL((u) => !u.pathname.startsWith("/login"), { timeout: 90000 });
await page.goto(`${BASE}/admin/ngos/a0000000-0000-4000-8000-000000000002`, { waitUntil: "domcontentloaded", timeout: 90000 });
await page.waitForLoadState("networkidle", { timeout: 60000 }).catch(() => {});
await page.waitForTimeout(1000);
const ov = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
await page.screenshot({ path: "/home/z/my-project/scripts/qa/shots-retheme/admin-ngo-detail-1280.png" });
console.log("admin-ngo-detail @1280 captured (overflow " + ov + "px, url " + page.url() + ")");
await browser.close();
